import 'dotenv/config';
import 'reflect-metadata';
import assert from 'node:assert/strict';
import {randomUUID,randomBytes} from 'node:crypto';
import {NestFactory} from '@nestjs/core';
import request from 'supertest';
const url=new URL(process.env.DATABASE_URL);
if(!['localhost','127.0.0.1'].includes(url.hostname)||url.pathname!=='/restaurant_integration_test')throw Error('Only restaurant_integration_test is allowed');
process.env.NODE_ENV='test';
const {AppModule}=await import('../dist/app.module.js');
const {PrismaService}=await import('../dist/prisma/prisma.service.js');
const {configureApp}=await import('../dist/main.js');
const {hashPassword,tokenHash}=await import('../dist/auth/password.js');
const app=await NestFactory.create(AppModule,{logger:false});
await configureApp(app);await app.init();
const db=app.get(PrismaService),server=app.getHttpServer();
assert.equal((await db.$queryRaw`SELECT current_database() AS name`)[0].name,'restaurant_integration_test');
const ids=Object.fromEntries(['branch','unit','category','location','material','lot','balance','staff'].map(k=>[k,randomUUID()]));
const suffix=ids.branch.slice(0,8),checks=[];
try{
  await db.branch.create({data:{id:ids.branch,code:'IT-ISSUE-'+suffix,name:'Staff Warehouse issue fixture'}});
  await db.unit.create({data:{id:ids.unit,name:'IT-UNIT-'+suffix}});
  await db.category.create({data:{id:ids.category,code:'IT-DM-'+suffix,name:'Issue fixture '+suffix,categoryType:'MATERIAL'}});
  await db.warehouseLocation.create({data:{id:ids.location,branchId:ids.branch,name:'Issue fixture',locationType:'RAW_MATERIAL'}});
  await db.material.create({data:{id:ids.material,code:'IT-NVL-'+suffix,name:'Issue fixture',unitId:ids.unit,categoryId:ids.category}});
  await db.materialLot.create({data:{id:ids.lot,materialId:ids.material,lotCode:'IT-LOT-'+suffix,expiryDate:new Date('2099-12-31')}});
  await db.materialBalance.create({data:{id:ids.balance,locationId:ids.location,materialLotId:ids.lot,quantity:'10'}});
  await db.staffUser.create({data:{id:ids.staff,code:'IT-STAFF-'+suffix,name:'Issue fixture',role:'KITCHEN',branchId:ids.branch,passwordHash:hashPassword(randomBytes(24).toString('hex'))}});
  const token=randomBytes(32).toString('hex');
  await db.staffSession.create({data:{tokenHash:tokenHash(token),userId:ids.staff,expiresAt:new Date(Date.now()+60000)}});
  const cookie='staff_session='+token;
  const staff=()=>request(server).get('/api/staff/production-orders/material-requests').set('Cookie',cookie);
  const stock=async()=>(await db.materialBalance.findUniqueOrThrow({where:{id:ids.balance}})).quantity.toString();
  const submit=async quantity=>{
    const r=await request(server).post('/api/staff/production-orders/material-requests').set('Cookie',cookie).set('X-Staff-Request','1').send({items:[{balanceId:ids.balance,quantity}]});
    assert.equal(r.status,201,JSON.stringify(r.body));assert.equal(r.body.status,'PENDING');
    await db.materialIssue.update({where:{issueCode:r.body.code},data:{createdAt:new Date(Date.now()-20*60000)}});
    assert.equal((await staff()).body.find(x=>x.code===r.body.code).processedAt,null);
    return r.body.code;
  };
  async function decisionTime(code) {
    const row=(await staff()).body.find(x=>x.code===code);
    const stored=await db.materialIssue.findUniqueOrThrow({where:{issueCode:code}});
    assert.ok(row.processedAt,'Staff must receive the decision timestamp');
    assert.equal(row.processedAt,stored.processedAt.toISOString());
    assert.ok(new Date(row.processedAt)-new Date(row.createdAt)>=19*60000);
    assert.ok(Math.abs(Date.now()-new Date(row.processedAt).getTime())<10000);
    return row.processedAt;
  }
  const rejected=await submit('2');
  assert.equal(await stock(),'10');
  const pending=await request(server).get('/warehouse/material-issues?status=PENDING');
  assert.equal(pending.status,200);assert.ok(pending.body.data.some(x=>x.issueCode===rejected));
  const detail=await request(server).get('/warehouse/material-issues/'+rejected);
  assert.equal(detail.status,200);assert.equal(detail.body.data.details[0].quantity,'2');
  assert.equal(await db.materialIssue.count({where:{issueCode:rejected}}),1);
  assert.equal((await request(server).post('/warehouse/material-issues/'+rejected+'/reject').send({})).status,400);
  let r=await request(server).post('/warehouse/material-issues/'+rejected+'/reject').send({reason:'Kho yêu cầu điều chỉnh số lượng'});
  assert.equal(r.status,200,JSON.stringify(r.body));
  const rejectedRow=(await staff()).body.find(x=>x.code===rejected);
  assert.equal(rejectedRow.status,'REJECTED');assert.ok(rejectedRow.note.includes('Kho yêu cầu điều chỉnh số lượng'));assert.equal(await stock(),'10');
  await decisionTime(rejected);
  checks.push('Staff submits -> same Warehouse issue -> rejection and reason returned; stock unchanged');
  const approved=await submit('3');
  assert.equal(await stock(),'10');
  r=await request(server).post('/warehouse/material-issues/'+approved+'/approve').send({});
  assert.equal(r.status,200,JSON.stringify(r.body));assert.equal(await stock(),'7');
  assert.equal((await staff()).body.find(x=>x.code===approved).status,'APPROVED');
  const approvedTime=await decisionTime(approved);
  const kitchen=(await db.$queryRaw`SELECT quantity::text FROM staff_kitchen_balances WHERE branch_id=${ids.branch}::uuid AND material_lot_id=${ids.lot}::uuid`)[0];
  assert.equal(Number(kitchen.quantity),3);
  assert.equal((await request(server).post('/warehouse/material-issues/'+approved+'/approve').send({})).status,409);
  assert.equal(await decisionTime(approved),approvedTime);
  assert.equal(await stock(),'7');assert.equal(await db.inventoryMovement.count({where:{materialLotId:ids.lot}}),1);
  checks.push('Approval decreases warehouse once, credits kitchen, and Staff reads APPROVED');
  const excessive=await request(server).post('/api/staff/production-orders/material-requests').set('Cookie',cookie).set('X-Staff-Request','1').send({items:[{balanceId:ids.balance,quantity:'8'}]});
  assert.equal(excessive.status,400);checks.push('Staff cannot request more than current stock');
  const shortage=await submit('6');
  await db.materialBalance.update({where:{id:ids.balance},data:{quantity:'1'}});
  r=await request(server).post('/warehouse/material-issues/'+shortage+'/approve').send({});
  assert.equal(r.status,400,JSON.stringify(r.body));
  assert.equal((await db.materialIssue.findUniqueOrThrow({where:{issueCode:shortage}})).status,'PENDING');
  assert.equal(await stock(),'1');assert.equal(await db.inventoryMovement.count({where:{materialLotId:ids.lot}}),1);
  assert.equal((await staff()).body.find(x=>x.code===shortage).processedAt,null);
  checks.push('Approval shortage rolls back status and creates no extra movement');
  checks.push('Actual decision time differs from creation by 20 minutes; rejected/approved timestamps persist, duplicate cannot rewrite, rollback stays null');
  console.log(JSON.stringify({database:'restaurant_integration_test',checks},null,2));
}finally{
  try{await db.$transaction(async tx=>{
    await tx.$executeRaw`DELETE FROM staff_kitchen_source_allocations WHERE issue_detail_id IN (SELECT d.id FROM material_issue_details d JOIN material_issues i ON i.id=d.issue_id WHERE i.branch_id=${ids.branch}::uuid)`;
    await tx.$executeRaw`DELETE FROM staff_kitchen_sources WHERE branch_id=${ids.branch}::uuid`;
    await tx.$executeRaw`DELETE FROM staff_kitchen_receipts WHERE branch_id=${ids.branch}::uuid`;
    await tx.$executeRaw`DELETE FROM staff_kitchen_balances WHERE branch_id=${ids.branch}::uuid`;
    await tx.staffAudit.deleteMany({where:{actorId:ids.staff}});
    await tx.inventoryMovement.deleteMany({where:{materialLotId:ids.lot}});
    await tx.materialIssueDetail.deleteMany({where:{issue:{branchId:ids.branch}}});
    await tx.materialIssue.deleteMany({where:{branchId:ids.branch}});
    await tx.staffSession.deleteMany({where:{userId:ids.staff}});
    await tx.staffUser.deleteMany({where:{id:ids.staff}});
    await tx.materialBalance.deleteMany({where:{id:ids.balance}});
    await tx.materialLot.deleteMany({where:{id:ids.lot}});
    await tx.material.deleteMany({where:{id:ids.material}});
    await tx.category.deleteMany({where:{id:ids.category}});
    await tx.unit.deleteMany({where:{id:ids.unit}});
    await tx.warehouseLocation.deleteMany({where:{id:ids.location}});
    await tx.branch.deleteMany({where:{id:ids.branch}});
  });}finally{await app.close();}
}
